export function groupColumns(c0: number, c1: number, keyFn: (ms: number) => number, origin = ORIGIN) {
    const groups: { firstCol: number; span: number; ms: number }[] = []
    let curKey: number | null = null
    for (let c = c0; c <= c1; c++) {
        const ms = addDays(origin, c)
        const k = keyFn(ms)
        if (k !== curKey) {
            curKey = k
            groups.push({ firstCol: c, span: 0, ms })
        }
        groups[groups.length - 1].span++
    }
    return groups
}

