const clamp = (v: number, lo: number, hi: number) => Math.max(lo, Math.min(v, hi))

// Pull image URLs out of a markdown issue body (`![alt](url)`), capped at 8.
function extractImages(md: string): string[] {
    if (!md) return []
    const out: string[] = []
    const re = /!\[[^\]]*\]\(\s*([^)\s]+)[^)]*\)/g
    let m: RegExpExecArray | null
    while ((m = re.exec(md)) !== null && out.length < 8) out.push(m[1])
    return out
}

// The body with image markdown stripped + whitespace collapsed.
function stripImages(md: string): string {
    if (!md) return ""
    return md.replace(/!\[[^\]]*\]\([^)]*\)/g, " ").replace(/\s+/g, " ").trim()
}

/** A scheduled brick's box in lattice pixels (col × cell, row × cell). */
export function brickBox(issue: DemoIssue, cell: number, origin = ORIGIN) {
    const col = Math.round((issue.start! - origin) / DAY)
    const days = Math.round((issue.end! - issue.start!) / DAY) + 1
    const span = issue.span ?? 1
    return {
        col, days, span, cols: tileCols(days),
        left: col * cell, top: issue.row! * cell, width: tileCols(days) * cell, trueWidth: days * cell, height: span * cell,
    }
}

/** The card (the real task, without the reserved tail) inside a brick's box. */
export function brickCard(box: { days: number; cols: number; span: number }, cell: number) {
    const inset = clamp(cell * 0.09, 2, 6)
    const radius = clamp(cell * 0.3, 8, 17)
    const width = box.cols > box.days ? box.days * cell : box.cols * cell - inset * 2
    return { left: inset, top: inset, width, height: box.span * cell - inset * 2, radius }
}

export function Brick({
    issue, cell, origin = ORIGIN, style, wrapIcon,
}: {
    issue: DemoIssue
    cell: number
    origin?: number // the board's day-0 column (boardOrigin)
    style?: CSSProperties // overrides the absolute placement (e.g. left/top 0 inside a mover)
    wrapIcon?: (icon: ReactNode) => ReactNode // wrap the label-icon square (e.g. to pop it in)
}) {
    const { col, days, span: rowSpan } = brickBox(issue, cell, origin) // inclusive end → stored ends_at is the next midnight
    const body = issue.body ?? ""
    const images = extractImages(body)

    const { bg, fg } = pastelFor(issue.id)
    const iconName = iconFor(issue)

    const inset = clamp(cell * 0.09, 2, 6)
    const radius = clamp(cell * 0.3, 8, 17)
    const studSize = clamp(cell * 0.12, 3, 8)
    const iconBox = clamp(cell * 0.4, 12, 22)
    const iconSize = clamp(cell * 0.24, 8, 13)
    const titleFont = clamp(cell * 0.3, 8, 15)
    const numFont = clamp(cell * 0.24, 7, 12)
    const descFont = clamp(cell * 0.26, 8, 12)
    const imgH = clamp(cell * 0.9, 18, 54)
    const studBand = studSize + 4
    const rowH = cell - inset * 2
    // Content tiers: 2+ lanes reveal the description, 3 lanes also thumbnails.
    const isTall = rowSpan >= 2
    const isXL = rowSpan >= 3
    const descText = isTall ? stripImages(body) : ""

    // Width: the true duration, or the readable minimum (MIN_TILE_COLS) with a
    // detached dashed "reserved" tail the label overflows onto.
    const visualCols = tileCols(days)
    const trueW = days * cell
    const visW = visualCols * cell
    const hasPad = visualCols > days
    const labelOnPad = hasPad
    const faintBg = `color-mix(in srgb, ${fg} 7%, transparent)`
    const dashColor = `color-mix(in srgb, ${fg} 34%, transparent)`
    const cardRing = `color-mix(in srgb, ${fg} 24%, transparent)`
    const padL = Math.max(5, cell * 0.13)
    const iconGap = Math.max(8, cell * 0.2)
    const iconSlotW = trueW > cell ? padL + iconBox + iconGap : cell
    const titleLeft = iconSlotW
    const titlePad = trueW > cell ? 0 : Math.max(9, cell * 0.2)
    const EASE = "cubic-bezier(0.22, 1, 0.36, 1)"

    // Whole description lines that fit, so a tall tile clamps on a line boundary.
    const descLineH = descFont * 1.375 // leading-snug
    const descAbove = studBand + iconBox + 6
    const descBelow = (isXL && images.length > 0 ? imgH + 6 : 0) + Math.max(5, cell * 0.16)
    const descLines = Math.max(1, Math.floor((rowSpan * cell - descAbove - descBelow) / descLineH))

    const titleRow = (
        <div className="flex shrink-0 items-center" style={{ height: rowH }}>
            {/* First cell — reserved for the icon. */}
            <div
                className={cx("flex shrink-0 items-center", trueW > cell ? "justify-start" : "justify-center")}
                style={{ width: iconSlotW, paddingLeft: trueW > cell ? padL : 0 }}
            >
                {(wrapIcon ?? ((icon: ReactNode) => icon))(
                    <span className="grid place-items-center rounded-[7px]" style={{ width: iconBox, height: iconBox, background: fg, boxShadow: `0 1px 2px ${cardRing}` }}>
                        {iconName && <LabelIcon name={iconName} size={Math.round(iconSize)} />}
                    </span>,
                )}
            </div>
            <span
                className="min-w-0 flex-1 truncate font-extrabold leading-none"
                style={{ fontSize: titleFont, paddingLeft: titlePad, transition: `padding-left 260ms ${EASE}` }}
            >
                {issue.title}
            </span>
            <span className="shrink-0 pl-1 pr-2 font-mono font-bold opacity-[0.45]" style={{ fontSize: numFont }}>
                #{issue.number}
            </span>
        </div>
    )

    const desc = (overlay: boolean) =>
        isTall && (
            <p
                className={cx("min-w-0 overflow-hidden leading-snug", overlay ? "font-semibold opacity-75" : "font-medium opacity-80")}
                style={{
                    fontSize: descFont,
                    marginTop: 2,
                    marginLeft: titleLeft,
                    paddingLeft: titlePad,
                    display: "-webkit-box",
                    WebkitBoxOrient: "vertical",
                    WebkitLineClamp: descLines,
                }}
            >
                {descText || "No description yet."}
            </p>
        )

    const thumbs = (overlay: boolean) =>
        isXL &&
        images.length > 0 && (
            <div className="mt-auto flex items-center gap-1 overflow-hidden pt-0.5" style={{ marginLeft: titleLeft, paddingLeft: titlePad }}>
                {images.slice(0, 4).map((src, i) => (
                    // eslint-disable-next-line @next/next/no-img-element
                    <img
                        key={i}
                        src={src}
                        alt=""
                        draggable={false}
                        className="shrink-0 rounded-[6px] object-cover"
                        style={{ height: imgH, width: imgH * 1.4, boxShadow: `0 0 0 1.5px ${cardRing}` }}
                    />
                ))}
                {!overlay && images.length > 4 && (
                    <span className="shrink-0 rounded-[5px] px-1 font-bold" style={{ fontSize: numFont, background: faintBg }}>
                        +{images.length - 4}
                    </span>
                )}
            </div>
        )

    return (
        <div
            data-brick
            className="touch-none"
            title={`${issue.title} • #${issue.number}`}
            style={{
                position: "absolute",
                left: col * cell,
                top: issue.row! * cell,
                width: visW,
                height: rowSpan * cell,
                padding: inset,
                transition: `top 220ms ${EASE}, left 220ms ${EASE}, width 220ms ${EASE}`,
                ...style,
            }}
        >
            <div className="group relative flex h-full w-full cursor-grab items-stretch gap-[3px]">
                {/* Card — the real task; its width IS the duration. */}
                <div
                    className="relative flex shrink-0 flex-col overflow-hidden"
                    style={{
                        width: hasPad ? trueW : "100%",
                        background: bg,
                        color: fg,
                        borderRadius: radius,
                        boxShadow: `0 0 0 1.5px ${cardRing}, 0 3px 8px -3px ${cardRing}`,
                    }}
                >
                    {labelOnPad ? (
                        <div className="min-h-0 flex-1" />
                    ) : (
                        <div className={cx("flex min-h-0 flex-1 flex-col pr-1.5", isTall && "pb-1")}>
                            {titleRow}
                            {desc(false)}
                            {thumbs(false)}
                        </div>
                    )}
                </div>

                {/* Reserved piece — detached, dashed, ghosted. */}
                {hasPad && (
                    <div
                        className="relative flex min-w-0 flex-1 overflow-hidden"
                        style={{ borderRadius: radius, border: `1.5px dashed ${dashColor}`, background: faintBg }}
                    />
                )}

                {/* Label overlay spanning both pieces (narrow tiles). */}
                {labelOnPad && (
                    <div
                        className="pointer-events-none absolute inset-0 flex flex-col overflow-hidden pr-1.5"
                        style={{ color: fg, paddingBottom: isTall ? Math.max(5, cell * 0.16) : 0 }}
                    >
                        {titleRow}
                        {desc(true)}
                        {thumbs(true)}
                    </div>
                )}
            </div>
        </div>
    )
}

// ─── Backlog tray (FloatingTray + TrayBrick) ─────────────────────────────────

function FloatingTray({ items }: { items: DemoIssue[] }) {
    return (
        <div data-ui className="pointer-events-none absolute inset-x-0 bottom-5 z-30 flex justify-center px-4">
            <TrayPill items={items} />
        </div>
    )
}

/** The backlog tray pill itself: 🎒 badge + chip row. `count` replaces the number. */
export function TrayPill({ items, count, blur = true }: { items: DemoIssue[]; count?: ReactNode; blur?: boolean }) {
    return (
        <div
            className={cx(
                "pointer-events-auto flex max-w-full items-center gap-2.5 rounded-[24px] p-2.5 shadow-[var(--shadow-pop)] ring-1 ring-[color:var(--c-border)]",
                blur && "backdrop-blur-[8px]",
            )}
            style={{ background: mix("--c-surface", 95) }}
        >
            <div className="flex shrink-0 items-center gap-1.5 rounded-full bg-[color:var(--c-shell)] px-3 py-1.5">
                <span className="text-[15px] leading-none">🎒</span>
                <span className="text-[10px] font-extrabold uppercase tracking-[0.08em] text-[color:var(--c-text-muted)]">Backlog · {count ?? items.length}</span>
            </div>
            <div className="flex items-center gap-2 overflow-x-auto py-0.5 pr-1">
                {items.map((issue) => (
                    <TrayBrick key={issue.id} issue={issue} />
                ))}
            </div>
        </div>
    )
}

export function TrayBrick({ issue }: { issue: DemoIssue }) {
    const { bg, fg } = pastelFor(issue.id)
    const cardRing = `color-mix(in srgb, ${fg} 24%, transparent)`
    const iconName = iconFor(issue)
    return (
        <div
            className="flex shrink-0 cursor-grab touch-none select-none items-center gap-2 rounded-full py-1.5 pl-1.5 pr-3 text-[11px] font-extrabold"
            style={{ background: bg, color: fg, boxShadow: `0 0 0 1.5px ${cardRing}, var(--shadow-card)` }}
            title={`${issue.title} • #${issue.number}`}
        >
            <span className="grid h-[19px] w-[19px] shrink-0 place-items-center rounded-full" style={{ background: fg }}>
                {iconName && <LabelIcon name={iconName} size={10} />}
            </span>
            <span className="max-w-[150px] truncate">{issue.title}</span>
        </div>
    )
}
