export function isoWeekNumber(ms: number): number {
    const u = new Date(ms)
    const day = u.getUTCDay() || 7
    u.setUTCDate(u.getUTCDate() + 4 - day)
    const yearStart = Date.UTC(u.getUTCFullYear(), 0, 1)
    return Math.ceil(((u.getTime() - yearStart) / DAY + 1) / 7)
}
